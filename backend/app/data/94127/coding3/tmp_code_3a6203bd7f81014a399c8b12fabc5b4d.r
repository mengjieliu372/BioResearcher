# Safe read helper (graceful on missing/invalid)
safe_read <- function(path, sep = "\t") {
  if (!file.exists(path)) {
    warning(sprintf("Missing file: %s. Using placeholder.", path))
    return(data.table())
  }
  out <- tryCatch({
    fread(path, sep = sep, data.table = TRUE)
  }, error = function(e) {
    warning(sprintf("Failed to read %s: %s. Using placeholder.", path, e$message))
    data.table()
  })
  return(out)
}

